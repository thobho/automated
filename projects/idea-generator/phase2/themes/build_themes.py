#!/usr/bin/env python3
"""T15: apply the theme taxonomy to the catalogue and compute per-theme stats.

Run from anywhere:  python3 projects/idea-generator/phase2/themes/build_themes.py [--write]
Without --write it only checks coverage and prints stats.
With --write it fills the `theme` column in every catalogue/*.csv (other columns, quoting,
line endings and row order preserved) and writes themes/mapping.csv and themes/stats.csv.
THEMES.md is generated by render_themes.py from stats.csv + taxonomy.py.
"""
import csv
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from taxonomy import THEMES, MEMBERS  # noqa: E402

CAT = os.path.join(HERE, "..", "catalogue")
SIG_RE = re.compile(r"^\s*(\d{1,2})\b")
YEAR_RE = re.compile(r"(?<!\d)(19\d\d|20\d\d)(?!\d)")


def load():
    files = {}
    for path in sorted(glob.glob(os.path.join(CAT, "*.csv"))):
        raw = open(path, "rb").read()
        crlf = b"\r\n" in raw
        with open(path, encoding="utf-8", newline="") as f:
            reader = csv.DictReader(f)
            rows = list(reader)
            files[path] = (reader.fieldnames, rows, crlf)
    return files


def signals(text):
    """Durable signal numbers recorded in a catalogue cell (1-10), as a set."""
    if not text or text.strip().lower().startswith(("unknown", "none")):
        return set()
    out = set()
    for seg in text.split(";"):
        m = SIG_RE.match(seg)
        if m and 1 <= int(m.group(1)) <= 10:
            out.add(int(m.group(1)))
    return out


HYPE_KEYS = {  # the brief's hype-warning list, matched by keyword; other text is a caveat
    "tourists/spike": ("tourist", "spike", "users vs"),
    "one-off/lifetime revenue": ("lifetime", "one-off", "appsumo"),
    "paid ads/influencers": ("paid ads", "influencer", "paid marketing", "paid-ads"),
    "novelty use case": ("novelty", "avatar", "companion", "generator"),
    "thin wrapper": ("wrapper",),
    "price cuts": ("price cut",),
    "layoffs/pivot": ("layoff", "pivot", "near-bankruptcy", "receivership", "insolven", "burn "),
}


def hype_kinds(text):
    """Hype-warning kinds from the brief's list found in a hype_warnings cell."""
    t = (text or "").lower()
    if t.startswith(("none", "unknown")):
        return []
    return [k for k, keys in HYPE_KEYS.items() if any(x in t for x in keys)]


def caveat(text):
    t = (text or "").strip().lower()
    return bool(t) and not t.startswith(("none", "unknown")) and not hype_kinds(text)


def label(sig, hype):
    """Durability label per criteria.md section 6 (signals as recorded in the catalogue)."""
    pts = len(sig) + (1 if 3 in sig else 0) + (1 if 4 in sig else 0)
    score = pts - 2 * hype
    if not sig and not hype:
        return "no-evidence", score
    if score <= 0:
        return "hype", score
    if score <= 3:
        return "unproven", score
    if score >= 7 and (3 in sig or 4 in sig):
        return "durable", score
    return "promising", score


def year(launched):
    ys = YEAR_RE.findall(launched or "")
    return int(ys[-1]) if ys else None


def main(write):
    files = load()
    tid = {}
    for t, ids in MEMBERS.items():
        for i in ids.split():
            if i in tid:
                sys.exit(f"duplicate id {i} in {tid[i]} and {t}")
            tid[i] = t
    known = {t[0] for t in THEMES}
    assert set(MEMBERS) == known, set(MEMBERS) ^ known
    all_ids = []
    for path, (_, rows, _) in files.items():
        all_ids += [r["id"] for r in rows]
    missing = [i for i in all_ids if i not in tid]
    extra = [i for i in tid if i not in set(all_ids)]
    dup = {i for i in all_ids if all_ids.count(i) > 1}
    if missing or extra or dup:
        sys.exit(f"missing {missing}\nextra {extra}\ndup ids in catalogue {dup}")

    stats = {t[0]: dict(rows=[]) for t in THEMES}
    for path, (fields, rows, crlf) in files.items():
        for r in rows:
            r["theme"] = tid[r["id"]]
            stats[r["theme"]]["rows"].append((os.path.basename(path), r))
        if write:
            if "theme" not in fields:
                fields = fields + ["theme"]
            with open(path, "w", encoding="utf-8", newline="") as f:
                w = csv.DictWriter(f, fieldnames=fields, quoting=csv.QUOTE_ALL,
                                   lineterminator="\r\n" if crlf else "\n")
                w.writeheader()
                w.writerows(rows)

    out = []
    for t in THEMES:
        th = t[0]
        members = stats[th]["rows"]
        labels, countries, regions, years, b2 = [], set(), set(), [], {}
        hkinds, ncav = set(), 0
        best = None
        for fname, r in members:
            sig = signals(r["durable_signals"])
            kinds = hype_kinds(r["hype_warnings"])
            hy = len(kinds)
            hkinds.update(kinds)
            ncav += caveat(r["hype_warnings"])
            lab, sc = label(sig, hy)
            labels.append(lab)
            countries.add(r["country"])
            regions.add(r["region"])
            y = year(r["launched"])
            if y:
                years.append(y)
            b2[r["b2b_b2c"]] = b2.get(r["b2b_b2c"], 0) + 1
            key = (sc, len(sig))
            if best is None or key > best[0]:
                best = (key, r["id"])
        cnt = {k: labels.count(k) for k in ("durable", "promising", "unproven", "hype", "no-evidence")}
        out.append(dict(
            theme=th, title=t[1], rows=len(members), countries=len(countries),
            regions=len(regions), country_list="; ".join(sorted(countries)),
            region_list=" ".join(sorted(regions, key=lambda x: int(x[1:]))),
            year_min=min(years) if years else "", year_max=max(years) if years else "",
            b2b_b2c="; ".join(f"{k} {v}" for k, v in sorted(b2.items(), key=lambda kv: -kv[1])),
            best_id=best[1], novelty=t[4], hype_kinds="; ".join(sorted(hkinds)), n_caveat=ncav, **{f"n_{k.replace('-', '_')}": v for k, v in cnt.items()},
        ))
    if write:
        with open(os.path.join(HERE, "mapping.csv"), "w", encoding="utf-8", newline="") as f:
            w = csv.writer(f, quoting=csv.QUOTE_ALL, lineterminator="\n")
            w.writerow(["id", "name", "catalogue_file", "theme"])
            for path, (_, rows, _) in files.items():
                for r in rows:
                    w.writerow([r["id"], r["name"], os.path.basename(path), r["theme"]])
        with open(os.path.join(HERE, "stats.csv"), "w", encoding="utf-8", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(out[0]), quoting=csv.QUOTE_ALL, lineterminator="\n")
            w.writeheader()
            w.writerows(out)
    for o in out:
        print(o["theme"], o["rows"], o["countries"], o["regions"], o["year_min"], o["year_max"],
              o["n_durable"], o["n_promising"], o["n_unproven"], o["n_hype"], o["n_no_evidence"], o["title"])
    print("rows", len(all_ids), "themes", len(THEMES))


if __name__ == "__main__":
    main("--write" in sys.argv)
