#!/usr/bin/env python3
"""Generate reports/bibliography.md and reports/citation-sheet.md from sources.csv
and the source_id columns of the data files.

  python3 scripts/build_reference_docs.py          # write both files
  python3 scripts/build_reference_docs.py --check  # exit 1 if they are out of date

Nothing is typed by hand: every reference line comes from a sources.csv row,
every caption from the ids a data file actually uses. Standard library only.
"""
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_sources as cs  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

# Raw extracts without a source_id column. Provenance = the sources whose BDL variable
# ids / Eurostat dataset codes appear in the file (matched against sources.csv).
RAW_PROVENANCE = {
    "bdl_housing_national.csv": ["S41", "S42", "S43", "S44", "S45", "S46", "S47", "S48"],
    "bdl_housing_powiats_big.csv": ["S46"],
    "bdl_housing_class_sums.csv": ["S41", "S42", "S43", "S44", "S45"],
    "bdl_structure_national.csv": ["S8", "S9", "S10", "S11", "S12", "S13", "S14", "S15", "S16", "S17", "S18"],
    "eurostat_europe.csv": ["S29", "S30", "S31", "S32", "S33", "S34", "S35"],
    "eurostat_poland.csv": ["S19", "S20", "S21", "S22", "S23", "S24"],
}


def sid_num(sid):
    return int(sid[1:])


def short_code(code):
    """First identifier of indicator_or_table_code: 'BDL subject P1336; variables ...' -> 'BDL subject P1336'."""
    return re.split(r";|:| \(", code, maxsplit=1)[0].strip()


def reference(row):
    """One full reference line for a sources.csv row."""
    parts = [f"**[{row['id']}]** {row['publisher']}. *{row['title']}*."]
    if row["indicator_or_table_code"]:
        parts.append(f"{row['indicator_or_table_code']}.")
    parts.append(f"<{row['url']}> (accessed {row['accessed']}).")
    return " ".join(parts)


def caption_part(row):
    code = short_code(row["indicator_or_table_code"])
    return f"{row['publisher']}, {code}, accessed {row['accessed']}, {row['url']}"


def caption(rows, derived, prefix="Source"):
    text = f"{prefix}: " + "; ".join(caption_part(r) for r in rows) + "."
    if derived:
        suffix = ("Wartości pochodne obliczone w projekcie (wzory w pliku)." if prefix == "Źródło"
                  else "Derived values calculated in this project (formulas in the file).")
        text += " " + suffix
    return text


def has_derived(path):
    with open(path, newline="", encoding="utf-8") as f:
        rd = csv.DictReader(f)
        if "value_type" not in (rd.fieldnames or []):
            return False
        return any("derived" in (r["value_type"] or "") for r in rd)


def row_count(path):
    with open(path, newline="", encoding="utf-8") as f:
        return sum(1 for _ in csv.DictReader(f))


def build_bibliography(root):
    root = Path(root)
    rows = cs.read_sources(root / "sources.csv")
    usage = cs.source_usage(root)
    out = ["# Bibliography", "",
           "_Generated by `scripts/build_reference_docs.py` from `sources.csv`; do not edit by hand._", "",
           f"{len(rows)} sources. Each key `[S..]` is the key used in the reports and in the `source_id` "
           "column of the data files. Access dates are the days the data or page was retrieved. "
           "\"Used in\" lists where the source is cited or used.", ""]
    for kind, title, blurb in (
            ("primary", "Primary sources", "Official statistics and the original publisher of a number."),
            ("secondary", "Secondary sources",
             "Articles and analyses: interpretation only, never the origin of a number.")):
        group = sorted((r for r in rows if r["type"] == kind), key=lambda r: sid_num(r["id"]))
        out += [f"## {title} ({len(group)})", "", blurb, ""]
        for r in group:
            u = usage.get(r["id"], {"reports": set(), "data": set()})
            used = []
            if u["reports"]:
                used.append("reports " + ", ".join(sorted(n.removesuffix(".md") for n in u["reports"])))
            if u["data"]:
                used.append("data " + ", ".join(sorted(u["data"])))
            out += [f"- {reference(r)}", f"  Used in: {'; '.join(used) if used else 'NOT USED'}."]
        out.append("")
    return "\n".join(out)


def build_citation_sheet(root):
    root = Path(root)
    rows = {r["id"]: r for r in cs.read_sources(root / "sources.csv")}
    out = ["# Citation sheet", "",
           "_Generated by `scripts/build_reference_docs.py` from `sources.csv` and the `source_id` columns "
           "of the data files; do not edit by hand._", "",
           "Ready-to-paste caption for every dataset file. English line `Source:`, Polish line `Źródło:` "
           "(the form the project design system uses). Where a file has derived values, say so in the "
           "caption (the formula is in the file's `formula` column). Full references: `bibliography.md`.", ""]
    processed = sorted((root / "data" / "processed").glob("*.csv"))
    out += [f"## Processed data ({len(processed)} files, `data/processed/`)", ""]
    for p in processed:
        ids = sorted(cs.source_ids_in_csv(p), key=sid_num)
        out += file_entry(p, ids, rows, has_derived(p))
    raws = sorted(p for p in (root / "data" / "raw").glob("*.csv"))
    out += [f"## Raw extracts ({len(raws)} files, `data/raw/`)", "",
            "Small committed extracts of API responses. Prefer citing the processed file. Files without a "
            "`source_id` column take their provenance from `RAW_PROVENANCE` in the generator script "
            "(sources whose variable ids or dataset codes occur in the file).", ""]
    for p in raws:
        ids = sorted(cs.source_ids_in_csv(p), key=sid_num) or RAW_PROVENANCE.get(p.name, [])
        out += file_entry(p, ids, rows, False)
    return "\n".join(out)


def file_entry(path, ids, rows, derived):
    entry = [f"### `{path.name}`", "", f"{row_count(path)} rows; sources: {', '.join(ids) if ids else 'NONE'}.", ""]
    if ids:
        chosen = [rows[i] for i in ids]
        entry += [f"> {caption(chosen, derived, 'Source')}", ">",
                  f"> {caption(chosen, derived, 'Źródło')}", ""]
    return entry


def main(argv):
    root = ROOT
    targets = {root / "reports" / "bibliography.md": build_bibliography(root),
               root / "reports" / "citation-sheet.md": build_citation_sheet(root)}
    if "--check" in argv:
        stale = [p.name for p, text in targets.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != text + "\n"]
        for name in stale:
            print(f"STALE {name}: run python3 scripts/build_reference_docs.py")
        return 1 if stale else 0
    for p, text in targets.items():
        p.write_text(text + "\n", encoding="utf-8")
        print(f"wrote {p.relative_to(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
